#!/usr/bin/env python3
"""CLI: skill-gap report from the eligible-jobs snapshot vs a profile.

Deterministic and offline: reads one JSON file (list of job dicts with
``title`` / ``description``), optionally reads a candidate-profile markdown
file (its text is never embedded in the generated report), and writes a
three-section markdown report:

  (a) top skills demanded by the market (by description frequency),
  (b) GAPS: skills the postings ask for but the profile does not show,
  (c) MATCHES: skills the profile already has that the market asks for.

Usage::

    python scripts/skill_gap_report.py \
        --input data/eligible_jobs.json \
        --profile /path/to/PERFIL.md \
        --top 40 --output report.md

``--profile`` is optional: without it only the market section is emitted.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

# Allow running from a source checkout without installing.
_SRC = Path(__file__).resolve().parents[1] / "src"
if _SRC.is_dir() and str(_SRC) not in sys.path:
    sys.path.insert(0, str(_SRC))

from internship_finder.skill_gap import gap_report, profile_text  # noqa: E402

SECTIONS = ("market", "gaps", "matches")


def _fmt_share(share: float) -> str:
    return f"{share * 100:.1f}%"


def _row(stat, rank: int, with_profile_col: bool) -> str:
    cells = [
        str(rank), stat.label, stat.category,
        str(stat.freq_title), str(stat.freq_desc), str(stat.freq_any),
        _fmt_share(stat.share_eligible),
    ]
    if with_profile_col:
        present = stat.present_in_profile
        cells.append("" if present is None else ("yes" if present else "NO"))
    return "| " + " | ".join(cells) + " |"


def _table_header(with_profile_col: bool) -> list:
    cols = ["#", "Skill", "Category", "freq title", "freq desc", "freq any", "share of eligible"]
    if with_profile_col:
        cols.append("in profile")
    return cols


def build_report(stats, n_jobs: int, n_desc: int, top: int, has_profile: bool) -> str:
    lines: list[str] = []
    lines.append("# Skill-gap report — internship market vs profile")
    lines.append("")
    lines.append(
        f"Universe: **{n_jobs} eligible jobs** ({n_desc} with a description). "
        "Deterministic dictionary matching; frequency is *mention*, not hard "
        "requirement (see docs/f28_skill_gap.md for methodology and limits)."
    )
    lines.append("")

    with_profile_col = has_profile

    def emit_table(title: str, rows: list, note: str = "") -> None:
        lines.append(title)
        lines.append("")
        if note:
            lines.append(note)
            lines.append("")
        if rows:
            cols = _table_header(with_profile_col)
            lines.append("| " + " | ".join(cols) + " |")
            lines.append("|" + "|".join(
                "---:" if c in ("#", "freq title", "freq desc", "freq any", "share of eligible") else "---"
                for c in cols) + "|")
            for i, s in enumerate(rows, 1):
                lines.append(_row(s, i, with_profile_col))
        else:
            lines.append("_No rows for this section._")
        lines.append("")

    # (a) market top skills — ordered by description frequency
    market = sorted(
        (s for s in stats if s.freq_desc > 0),
        key=lambda s: (-s.freq_desc, s.skill),
    )[:top]
    emit_table(
        f"## 1. Top skills in the market (top {top} by description frequency)",
        market,
        "How often each skill is mentioned across posting titles and descriptions.",
    )

    if has_profile:
        # (b) gaps — asked by the market, absent from the profile
        gaps = sorted(
            (s for s in stats if s.freq_any > 0 and s.present_in_profile is False),
            key=lambda s: (-s.share_eligible, s.skill),
        )[:top]
        emit_table(
            f"## 2. GAPS — asked by the market, not present in the profile (top {top})",
            gaps,
            "Ranked by share of eligible postings that mention the skill. "
            "These are the upskilling candidates.",
        )

        # (c) matches — the profile already shows what the market asks
        matches = sorted(
            (s for s in stats if s.freq_any > 0 and s.present_in_profile is True),
            key=lambda s: (-s.share_eligible, s.skill),
        )[:top]
        emit_table(
            f"## 3. MATCHES — the profile already shows what the market asks (top {top})",
            matches,
            "Reinforcement: keep these sharp, they are market currency.",
        )

    lines.append("<!-- generated by scripts/skill_gap_report.py — deterministic output -->")
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(
        description="Skill-gap report: eligible-jobs snapshot vs candidate profile (deterministic, offline)."
    )
    parser.add_argument("--input", required=True,
                        help="eligible_jobs.json (list of job dicts)")
    parser.add_argument("--profile", default=None,
                        help="optional candidate-profile markdown (never embedded in the report)")
    parser.add_argument("--top", type=int, default=40, help="rows per section")
    parser.add_argument("--output", default="-",
                        help="output path; '-' writes to stdout")
    args = parser.parse_args(argv)

    with open(args.input, "r", encoding="utf-8") as fh:
        jobs = json.load(fh)
    if not isinstance(jobs, list):
        raise SystemExit(f"expected a JSON list of jobs in {args.input}")

    prof_text = profile_text(args.profile) if args.profile else None
    stats = gap_report(jobs, profile_text=prof_text)
    n_desc = sum(1 for j in jobs if (j.get("description") or "").strip())
    report = build_report(stats, len(jobs), n_desc, args.top, prof_text is not None)

    if args.output == "-":
        sys.stdout.write(report)
    else:
        Path(args.output).write_text(report, encoding="utf-8")
        print(f"report written to {args.output}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
